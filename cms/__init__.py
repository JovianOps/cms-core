#!/usr/bin/env python3
"""cms-core: A minimal CMS to beat Drupal."""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any, Dict, Optional, Tuple, List

import markdown
from jinja2 import Environment, FileSystemLoader

__version__ = "1.0.0"

DEFAULT_THEME = """\
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>{{ title }}</title>
</head>
<body>
  <header>
    <h1>{{ site.title }}</h1>
  </header>
  <main>
    {{ content | safe }}
  </main>
  <footer>
    <small>Generated by cms-core {{ version }}</small>
  </footer>
</body>
</html>
"""

DEFAULT_CONFIG = """\
site:
  title: My Site
  author: ""
  lang: en

theme: default
"""

DEFAULT_INDEX = """\
---
title: Home
---
Welcome to my site.

Edit `content/index.md` to change this page.
"""


def find_root(start: Path = None) -> Path:
    """Find the nearest directory containing a .cms/ marker."""
    path = (start or Path.cwd()).resolve()
    for parent in [path] + list(path.parents):
        if (parent / ".cms").exists():
            return parent
    return path


def init_project(root: Path) -> None:
    """Initialize a new CMS project."""
    root.mkdir(parents=True, exist_ok=True)
    (root / ".cms").mkdir(exist_ok=True)

    config_file = root / "cms.yaml"
    if not config_file.exists():
        config_file.write_text(DEFAULT_CONFIG)

    content_dir = root / "content"
    content_dir.mkdir(exist_ok=True)

    index = content_dir / "index.md"
    if not index.exists():
        index.write_text(DEFAULT_INDEX)

    themes_dir = root / "themes"
    default_theme = themes_dir / "default"
    default_theme.mkdir(parents=True, exist_ok=True)
    (default_theme / "base.html").write_text(DEFAULT_THEME)

    print(f"Initialized CMS project at {root}")


def load_config(root: Path) -> Dict[str, Any]:
    """Load cms.yaml config (minimal parser, no PyYAML dependency)."""
    config_file = root / "cms.yaml"
    if not config_file.exists():
        return {"site": {"title": "My Site"}, "theme": "default"}

    config: Dict[str, Any] = {}
    current_section: Optional[str] = None

    for line in config_file.read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not line.startswith(" ") and ":" in stripped:
            key, _, value = stripped.partition(":")
            key, value = key.strip(), value.strip()
            current_section = None
            if not value:
                config[key] = {}
                current_section = key
            else:
                config[key] = value
        elif current_section and ":" in stripped:
            key, _, value = stripped.partition(":")
            config.setdefault(current_section, {})[key.strip()] = value.strip()

    if "site" not in config:
        config["site"] = {"title": "My Site"}
    if "theme" not in config:
        config["theme"] = "default"
    return config


def _parse_frontmatter(text: str) -> Tuple[Dict[str, Any], str]:
    """Parse YAML frontmatter from markdown. Returns (metadata, body)."""
    if not text.startswith("---\n"):
        return {}, text

    end = text.find("\n---", 4)
    if end == -1:
        return {}, text

    fm_text = text[4:end]
    body = text[end + 5:]

    fm: Dict[str, Any] = {}
    for line in fm_text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" in line:
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip()

    return fm, body


def build_site(root: Path, config: Dict[str, Any], output_dir: Path) -> None:
    """Build static site from content/ directory."""
    content_dir = root / "content"
    if not content_dir.exists():
        print(f"Error: content directory not found at {content_dir}", file=sys.stderr)
        sys.exit(1)

    theme_dir = root / "themes" / config.get("theme", "default")

    env = Environment(
        loader=FileSystemLoader([str(theme_dir), str(content_dir)]),
        autoescape=True,
        keep_trailing_newline=True,
    )
    template = env.get_template("base.html")

    site = config.get("site", {})
    output_dir.mkdir(parents=True, exist_ok=True)

    pages_built = 0
    for md_file in content_dir.rglob("*.md"):
        rel = md_file.relative_to(content_dir)
        html_file = output_dir / (rel.stem + ".html")

        text = md_file.read_text(encoding="utf-8")
        fm, body = _parse_frontmatter(text)
        content = markdown.markdown(body, extensions=["extra", "fenced_code"])

        html = template.render(
            content=content,
            title=fm.get("title", rel.stem.title()),
            site=site,
            version=__version__,
        )
        html_file.parent.mkdir(parents=True, exist_ok=True)
        html_file.write_text(html, encoding="utf-8")
        pages_built += 1

    print(f"Built {pages_built} pages to {output_dir}")


def serve_site(root: Path, config: Dict[str, Any], port: int = 8000) -> None:
    """Serve site dynamically."""
    import http.server
    from urllib.parse import urlparse

    output_dir = root / "dist"
    if not output_dir.exists():
        output_dir.mkdir(parents=True)
        build_site(root, config, output_dir)

    os.chdir(output_dir)
    server = http.server.HTTPServer(("localhost", port), http.server.SimpleHTTPRequestHandler)
    print(f"Serving on http://localhost:{port}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
        server.shutdown()


def main(argv: Optional[List[str]] = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(
        prog="cms",
        description="Minimal CMS: markdown content + Jinja2 templates",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    parser.add_argument("--root", type=Path, default=None,
                        help="Path to CMS project root")

    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("init", help="Initialize a new CMS project")
    build_p = sub.add_parser("build", help="Build static site")
    build_p.add_argument("--output", "-o", type=Path, default=None)
    serve_p = sub.add_parser("serve", help="Serve site locally")
    serve_p.add_argument("--port", "-p", type=int, default=8000)

    args = parser.parse_args(argv)

    root = args.root or find_root()

    if args.command == "init":
        if not (root / ".cms").exists():
            init_project(root)
            return 0
        else:
            print(f"CMS project already exists at {root}", file=sys.stderr)
            return 1
    elif not (root / ".cms").exists():
        print(f"Error: no CMS project found in {root}. Run 'cms init' first.", file=sys.stderr)
        return 1

    config = load_config(root)

    if args.command == "build":
        output = args.output or (root / "dist")
        build_site(root, config, output)
    elif args.command == "serve":
        serve_site(root, config, args.port)

    return 0


if __name__ == "__main__":
    sys.exit(main())
